def get_local_product_rules() -> list[dict]:
    return PRODUCT_RULES.copy()


def _build_search_haystack(item: dict) -> str:
    return normalize_text(
        " ".join(
            [
                item.get("product_name", ""),
                item.get("brand", ""),
                item.get("category", ""),
                item.get("variant_label", ""),
            ]
        )
    )


def _matches_department(item: dict, normalized_department: str) -> bool:
    if not normalized_department:
        return True
    item_departments = [normalize_text(name) for name in item.get("department_names", [])]
    return normalized_department in item_departments


def search_local_catalog(
    query: str,
    department: str = "",
    limit: int = DEFAULT_LOCAL_SEARCH_LIMIT,
) -> list[dict]:
    term = normalize_text(query)
    normalized_department = normalize_text(department)
    if len(term) < 2:
        return []

    results = []
    for item in LOCAL_CATALOG_ITEMS:
        haystack = _build_search_haystack(item)
        if term not in haystack:
            continue
        if not _matches_department(item, normalized_department):
            continue
        results.append(item)
        if len(results) >= limit:
            break
    return results


def lookup_local_by_barcode(barcode: str) -> dict | None:
    code = "".join(char for char in (barcode or "") if char.isdigit())
    if not code:
        return None
    for item in LOCAL_CATALOG_ITEMS:
        if item.get("barcode") == code:
            return item
    return None



